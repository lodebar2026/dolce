fn table() -> &'static HashMap<char, char> {
    static T: OnceLock<HashMap<char, char>> = OnceLock::new();
    T.get_or_init(|| {
        let mut m = HashMap::new();
        for t in [PAIRS, JP_PAIRS] {
            let cs: Vec<char> = t.iter().flat_map(|s| s.chars()).collect();
            for p in cs.as_chunks::<2>().0 {
                m.insert(p[0], p[1]);
            }
        }
        m
    })
}

/// 该字若是繁体（或日文新字体），返回它的简体形；否则 None
pub fn simplified_of(c: char) -> Option<char> {
    table().get(&c).copied()
}

