export interface NotationExample {
  /** 小节标题。 */
  title: string;
  /** 「常用」或「进阶」定位标签。 */
  level: "常用" | "进阶";
  /** 说明段落（支持 **粗** 与 `代码`）。 */
  body: string[];
  /** 展示给用户看的源码。 */
  code: string;
  /** 实际渲染的完整源码；缺省时由各格式的默认包裹补上头部。false = 只给源码不渲染。 */
  render?: string | false;
  /** 渲染独立的标题页（展示标题/词曲版式）而非乐谱内容页。 */
  titlePage?: boolean;
}

